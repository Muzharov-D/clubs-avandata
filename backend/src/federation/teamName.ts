/**
 * Нормализация имени команды для сшивки источников.
 *
 * Единая таблица федерации сшивает ПОЗИЦИЮ (официальный API ФФСПб) с РЕЙТИНГОМ
 * (АванДата). id у источников — РАЗНЫЕ пространства (АванДата 49–55, ФФСПб 420611+),
 * поэтому сшивка идёт ТОЛЬКО по имени. А источники именуют клуб по-разному, поэтому
 * срезаем весь шум именования к единому ключу:
 *   кавычки · «ФК» · хвостовой год рождения · скобочную приписку-программу
 *   «(Олимпийские надежды)» · город-квалификатор «СПб/Санкт-Петербург».
 *
 * Иначе клуб ДВОИТСЯ: строка таблицы без рейтинга + «призрак» с рейтингом, а колонка Δ
 * считается на неполных данных (баг 2012: «Звезда (Олимпийские надежды)» ≠ «ФК Звезда 2012»,
 * «ФК Динамо-СПб» ≠ «ФК Динамо 2012»).
 *
 * НО СШ/СШОР НЕ схлопываем — это разные школы (СШ ≠ СШОР). Кириллический `\b` в JS не
 * работает (ASCII-only), поэтому токен «спб» якорим пробелами/границами строки.
 *
 * Контракт зафиксирован тестами в `teamName.test.ts` — не ослаблять без обновления тестов.
 */
export const normTeam = (s: string): string => s.toLowerCase()
  .replace(/[«»"']/g, '')
  .replace(/\([^)]*\)/g, ' ')                            // «(Олимпийские надежды)» — программа, не имя
  .replace(/^фк\s+/, '')
  .replace(/\s*\d{4}\s*$/, '')                           // хвостовой год рождения (АванДата)
  .replace(/[-–—]/g, ' ')
  .replace(/(^|\s)(спб|санкт петербург)(?=\s|$)/g, ' ')  // город-квалификатор (ФФСПб даёт, АванДата нет)
  .replace(/\s+/g, ' ').trim();
