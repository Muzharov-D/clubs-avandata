-- =============================================================================
-- 0022 Личная ссылка входа для игрока — вход без пароля.
--
-- Решение владельца: ребёнок не должен придумывать и помнить пароль. Тренер
-- отдаёт ему постоянную личную ссылку, по ней игрок сразу попадает в свой
-- кабинет. Ссылка не одноразовая (в отличие от invite_token_hash из 0005):
-- её можно сохранить в закладки и открывать хоть каждый день.
--
-- Храним ТОЛЬКО sha256 токена: утечка дампа не даёт войти.
-- Обновление ссылки = запись нового хэша, старая мгновенно перестаёт работать.
--
-- Идемпотентно: ADD COLUMN IF NOT EXISTS.
-- =============================================================================

ALTER TABLE users ADD COLUMN IF NOT EXISTS link_token_hash text;
ALTER TABLE users ADD COLUMN IF NOT EXISTS link_issued_at  timestamptz;

-- Поиск идёт по хэшу при каждом входе по ссылке — без индекса это seq scan.
CREATE UNIQUE INDEX IF NOT EXISTS users_link_token_hash_idx
  ON users (link_token_hash) WHERE link_token_hash IS NOT NULL;
