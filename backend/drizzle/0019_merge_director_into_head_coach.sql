-- =============================================================================
-- 0019 Слияние роли sporting_director в head_coach.
--
-- Продуктовое решение: «спортивный директор» и «старший тренер» сведены в ОДНУ
-- роль (head_coach, титул «Старший тренер») с единым клубным кабинетом. Бывшие
-- спортдиректоры получают полные права старшего тренера (запись по всему клубу).
--
-- Идемпотентно: повторный прогон — no-op (директоров уже не остаётся).
-- CHECK-constraint НЕ трогаем — значение 'sporting_director' остаётся валидным,
-- но более не назначается (нулевой риск пересоздания constraint).
-- =============================================================================

UPDATE users SET role = 'head_coach', team_id = NULL WHERE role = 'sporting_director';
