-- Чистка служебных «имён»-заглушек в players.full_name (например, «U16»),
-- которые осели, когда имя игрока не распозналось при загрузке (пустой Excel).
-- Меняем ТОЛЬКО заглушки на «№NN» — реальные имена (с буквами) не трогаем.
--
-- Идемпотентно: '№08' снова попадает под паттерн и переписывается в то же значение.
-- Латинская 'u' в ~* не матчит кириллическую «У» — настоящие фамилии безопасны.

UPDATE players
   SET full_name = '№' || lpad(number::text, 2, '0'),
       first_name = NULL,
       last_name  = '№' || lpad(number::text, 2, '0')
 WHERE number IS NOT NULL
   AND (
     full_name ~* '^u[-[:space:]]?[0-9]{1,3}$'   -- U16, U-15, U 14
     OR full_name ~ '^№?[[:space:]]*[0-9]+$'      -- №8, 8
     OR btrim(full_name) = ''
   );
