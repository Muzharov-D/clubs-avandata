/**
 * Единая обрезка возрастной группы из названия команды для display.
 * Раньше логика была продублирована в 3 местах (MatchDetail/PlayerDetail/
 * ClubDashboard) и расходилась: старый регэксп `\s+20\d{2}` обрезал только
 * первый год с пробелом впереди → «Выборжанин 2010-2011» давал «Выборжанин -2011».
 *
 * Убирает: U15 / U-15 / 2011 / 2010-2011 (диапазон годов с любыми тире/пробелами),
 * а также кавычки «». Оставляет только название клуба.
 */
export function trimAgeSuffix(s: unknown): string {
  return String(s ?? '')
    .replace(/[«»"]/g, '')
    .replace(/[\s\-–—]*(?:[Uu]-?\s*\d{1,3}|20\d{2}(?:\s*[-–—]\s*20\d{2})?)/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Чистое имя команды для ОТОБРАЖЕНИЯ — надмножество trimAgeSuffix.
 * Календарь ФФСПБ/Наградиона даёт «грязные» имена: «ФК Легирус (ЦФКСиЗ ВО)»,
 * «ГБУ ДО СШОР №2 Невского района». Помимо возраста/кавычек убираем:
 *  - ведущую юр-форму (ФК/ГБУ ДО/ГБОУ/…), но НЕ «СШОР/СШ» — это часть имени;
 *  - хвостовую скобку-уточнение «(ЦФКСиЗ ВО)» (организация/площадка).
 * Сравнение имён — отдельной normalizeTeamName в utils/legirus (с алиасами).
 */
export function cleanTeamName(s: unknown): string {
  return String(s ?? '')
    .replace(/\s*\([^)]*\)\s*$/g, ' ')                                  // хвостовая (ЦФКСиЗ ВО)
    .replace(/^\s*(?:ФК|ГБУ\s+ДО|ГБОУ|МБОУ|МАОУ|ГКУ|МКУ|ГКОУ|АНО|ОО|РОО)\s+/i, '') // юр-форма
    .replace(/[«»"]/g, '')
    .replace(/[\s\-–—]*(?:[Uu]-?\s*\d{1,3}|20\d{2}(?:\s*[-–—]\s*20\d{2})?)/g, ' ')   // возраст
    .replace(/\s+/g, ' ')
    .trim();
}
